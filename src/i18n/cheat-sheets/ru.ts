// src/i18n/cheat-sheets/ru.ts
//
// Russian prose for the cheat sheets. See src/i18n/cheat-sheets.ts for how this
// overlays onto the English structure and why it is shaped this way.
//
// Terminology follows docs/i18n/glossary-ru.md. The decisions that matter most
// here, because they recur:
//
//   агрегатное состояние · реагенты / продукты · уравнять уравнение ·
//   коэффициент vs. индекс (the contrast the balancing topic turns on) ·
//   ковалентная / ионная / металлическая связь · неподелённая пара / общая
//   пара · формула Льюиса · многоатомный ион · ион гидроксония (H3O+) ·
//   молярная масса · количество вещества · реагент в недостатке ·
//   теоретический / практический / процентный выход · функциональная группа ·
//   сложный эфир (never *эфир* alone, which is an ether).
//
// Register: informal «ты», school-level vocabulary, Russian typography
// (« … » with no inner spaces, — with spaces, … as one character, **decimal
// comma throughout** — 6,02 × 10²³, 24,8 л/моль, 109,5° — and ё written out).
//
// **This overlay has 21 sections, matching the English exactly**, with four in
// `lewis-structures`. That was counted by hand against
// src/lib/cheat-sheet-data.ts as well as machine-checked: the overlay-shape
// gate in cheat-sheets.test.ts exists because the German `lewis-structures`
// overlay once shipped with three sections against four English ones, which
// renders every heading over the wrong body and passes every other assertion.
//
// Two sheets are **adapted, not translated** — the user's decision, recorded in
// docs/i18n/GAMES.md and the brief:
//
//   * `naming-compounds`. English teaches "-ide → hydro-…-ic acid". Russian has
//     no counterpart to that shape at all: it names binary acids after the
//     element plus **-водородная** (*хлороводородная*, *сероводородная*) and,
//     for the three school acids, by tradition instead (*соляная*,
//     *плавиковая*). The -ate/-ite pair becomes **-ная / -истая**
//     (*серная* / *сернистая*, *азотная* / *азотистая*), which is a suffix
//     contrast on the *acid*, where English's is on the *anion*. The acid-names
//     table teaches the Russian pattern. The molecular-naming rule had to be
//     restated from the other end, because Russian names molecular compounds
//     **anion first with the cation in the genitive** (*оксид углерода(IV)*),
//     so "drop mono- on the first element" becomes a note about the Stock
//     Roman numeral, which is what Russian school chemistry actually uses in
//     place of the Greek prefixes for the common oxides.
//   * `organic-nomenclature`. Russian names esters the other way round
//     (*метилацетат* / *метилэтаноат*, not "methyl ethanoate"), writes
//     carboxylic acids as *…овая кислота* and amines as *-амин*. The root table
//     is the Russian one (мет-, эт-, проп-, бут-), and the locant punctuation
//     rule is the Russian one: numbers are joined to words with hyphens and to
//     each other with commas, exactly as in English, but the suffix is written
//     *пропан-2-ол* with no space.
//
// `functional-groups` is partially adapted — the suffixes are Russian, the
// chemistry is not. There are **no English glosses in parentheses** anywhere:
// the user chose adaptation, not bilingual presentation.
//
// Not translated anywhere in this file: formulae, element symbols, state
// symbols, charges, structural notation (C–OH, –CHO), and physical quantities
// and their symbols (n, m, M, c, V, P, R, T).
//
// **This file carries no `curriculumRef` and no resource descriptions.** Both
// were here until 2026-09-20 and both were translated: the curriculum line
// cites one Australian state's syllabus, and every linked resource is an
// English-language page. Translating them put material in front of a student
// that the student cannot use. `src/i18n/cheat-sheets.ts` now withholds both
// from every locale but English, and the note there says why; the follow-up
// research is in docs/i18n/README.md § Locale-appropriate content.
//
// **Every adapted sheet is rated low in ru-review.md and needs a chemistry
// teacher who teaches in Russian to check it.** That is not a formality: the
// naming rules are content design per locale, not translation.

