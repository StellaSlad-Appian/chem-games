// src/i18n/chemistry-names/ru.ts
//
// Russian names for the chemistry registries.
//
// This is kept apart from the UI dictionary on purpose. The English names are
// already the canonical data in src/core-engine/data/, so duplicating them into
// an `en` dictionary would create a second source of truth that can drift from
// the registry. Instead each non-default locale supplies an *overlay*, keyed by
// the registry's own identifiers, and `src/i18n/chemistry-names.test.ts` asserts
// the overlay is complete against the live registries.
//
// What is NOT here, and must never be: formulae (H2SO4), element symbols (Na),
// state symbols ((aq), (s)) and charges. Those are international notation, and
// Russian chemistry writes them in Latin exactly as English does — the names
// beside them are Cyrillic.
//
// What Russian does, all of it fixed in docs/i18n/glossary-ru.md:
//
//   * Compounds compose **anion first, then the cation in the genitive**:
//     *гидроксид натрия*, *хлорид кальция*. French, Spanish and Italian reach
//     the same order with a preposition (*de* / *di*); Russian does it with a
//     case ending. That matters for the rest of the system: the genitive is
//     baked into the stored string, so a compound name is usable as-is where
//     an element name is not.
//   * **Mineral acids are named after the solution**, as in German: HCl is
//     **соляная кислота** (the systematic *хлороводородная* exists and is not
//     what a school textbook prints), HF is **плавиковая кислота**. The
//     corresponding **gases** are *хлороводород* and *фтороводород*, which is
//     what a compound card or a reaction description shows when the substance
//     is not in water. English loses this distinction; Russian and German both
//     keep it.
//   * Ions use the systematic **гидро-** prefix where the English data still
//     says *bi-*: bicarbonate is *гидрокарбонат*, bisulfate *гидросульфат*,
//     bisulfite *гидросульфит*, hydrosulfide *гидросульфид*.
//   * A monoatomic cation is *ион* + the element **in the genitive**
//     (*ион натрия*), which is why those read as two words where the anions
//     are one.
//   * **No *ди-* forms for the elemental gases**, matching Italian and German
//     rather than French and Spanish: H2 is *водород*, O2 *кислород*, N2
//     *азот*, Cl2 *хлор*. Russian school chemistry does not teach *диводород*
//     at all — it is not a register choice, the word is simply not used. The
//     cost is the one English already pays: the Reaction Balancer's **card** (a
//     substance) and its **atom ledger** (atoms) show the same word.
//   * Oxides use the Greek prefixes consistently — **оксид**, **монооксид**,
//     **диоксид** — with the Stock notation in Roman numerals where the
//     valency varies (*оксид железа(III)*, *нитрат меди(II)*). Russian school
//     books write both *оксид углерода(IV)* and *углекислый газ* for CO2; the
//     systematic form is used here, because that is what an equation needs,
//     and *углекислый газ* is noted in ru-review.md.
//
// Two things Russian does NOT need, stated because their absence is a decision
// and both were checked entry by entry rather than inherited:
// all fourteen `mustDiffer` element names are genuinely different — **натрий**,
// **калий**, **азот**, **кислород**, **углерод**, **водород**, **железо**,
// **медь**, **свинец**, **вольфрам**, **ртуть**, **серебро**, **олово**,
// **сера** — so there is no `SAME_AS_ENGLISH` entry; and all 35 compounds
// differ from the English, because N2H4 is **гидразин**, so there is no
// `IDENTICAL_COMPOUNDS_BY_DESIGN` entry either.

